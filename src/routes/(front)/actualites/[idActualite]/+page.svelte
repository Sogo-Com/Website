Pour reprendre une définition très ancienne de la communication, datant de l’époque des télégraphes, “communiquer c’est transmettre un message d'un émetteur vers un récepteur”. Évidemment, cette vieille définition a des lacunes aujourd’hui. Les situations de communication sont en réalité bien plus complexes. D’autres facteurs internes et externes interviennent.
<br><br>
Mais pour simplifier, cette histoire d'émetteur, de récepteur et de message, est une bonne base de travail.
L'émetteur, c’est moi, mon entreprise, ma marque…
Le récepteur, c’est mon client ou mon prospect
Le message, c’est ce que j’ai à dire, à vendre, à présenter, à défendre.
<br><br>
Une stratégie de communication est donc une construction liée à “qui je suis”, à “qui je m’adresse” et “qu’est-ce que je veux dire”.
<br><br>
